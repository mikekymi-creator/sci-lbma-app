import {test,expect} from "@playwright/test";

test("V0.2 desktop: exactly two properties, same-basis calculations and restored saved conditions",async({page})=>{
 await page.setViewportSize({width:1440,height:960});
 const backend:string[]=[];
 page.on("request",r=>{if(/supabase[.]|\/api\/|\/rest\/v1/.test(r.url()))backend.push(r.url());});
 await page.goto("./");
 await expect(page.getByRole("heading",{name:"Tableau de bord"})).toBeVisible();
 await page.getByRole("navigation",{name:"Navigation principale"}).getByRole("button",{name:"Mes biens"}).click();
 await expect(page.getByRole("button",{name:"Comparer (0/2)"})).toBeDisabled();
 await page.getByRole("checkbox",{name:"Sélectionner DÉMO · Appartement Beauvais"}).check();
 await expect(page.getByRole("button",{name:"Comparer (1/2)"})).toBeDisabled();
 await page.getByRole("checkbox",{name:"Sélectionner DÉMO · Maison multi-lots Valenciennes"}).check();
 await expect(page.getByRole("button",{name:"Comparer (2/2)"})).toBeEnabled();
 await page.getByRole("button",{name:"Comparer (2/2)"}).click();
 await expect(page.getByRole("heading",{name:"Bien A vs Bien B"})).toBeVisible();
 await expect(page.getByText("Cash-on-cash annuel avant IS")).toHaveCount(2);
 const snapshot=await page.locator(".rb-compare-summary").innerText();
 await page.getByRole("button",{name:"Hypothèses identiques"}).click();
 await expect(page.getByRole("heading",{name:"Hypothèses communes"})).toBeVisible();
 await page.getByLabel("Commun : Taux nominal").fill("2.5");
 await page.getByLabel("Commun : Durée du prêt").fill("25");
 await page.getByLabel("Commun : Vacance locative").fill("1.5");
 await page.getByRole("radio",{name:"Pourcentage du coût (%)"}).check();
 await page.getByLabel("Apport commun").fill("25");
 await expect(page.locator(".rb-compare-summary")).not.toHaveText(snapshot);
 await expect(page.getByText("Le pourcentage d'apport", {exact:false})).toHaveCount(0);
 await page.getByRole("button",{name:"Conditions propres"}).click();
 await expect(page.locator(".rb-compare-summary")).toHaveText(snapshot);
 await page.getByRole("button",{name:"Remplacer le bien B"}).click();
 await expect(page.getByRole("button",{name:"Comparer (1/2)"})).toBeDisabled();
 await page.getByRole("checkbox",{name:"Sélectionner DÉMO · Appartement Beauvais"}).toBeChecked();
 expect(backend).toEqual([]);
});
