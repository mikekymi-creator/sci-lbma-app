import {test,expect} from "@playwright/test";
test("mobile preview: finance, photos, comments, visit, persistence and PDF",async({page})=>{
 await page.setViewportSize({width:390,height:844});
 const unexpected:string[]=[];
 page.on("request",request=>{if(/supabase[.]|\/rest\/v1|\/api\//.test(request.url()))unexpected.push(request.url());});
 await page.goto("./");
 await expect(page.getByText("LBMA · TEST 0.2",{exact:true})).toBeVisible();
 await expect(page.getByRole("heading",{name:"DÉMO · Appartement Beauvais",exact:true})).toBeVisible();
 await page.screenshot({path:"test-results/preview-dashboard-mobile.png",fullPage:true});
 await page.getByRole("button",{name:"Ouvrir la fiche ↗"}).first().click();
 const dialog=page.getByRole("dialog");
 await dialog.getByLabel("Apport (€)",{exact:true}).fill("20000");
 await dialog.getByRole("combobox",{name:"Statut",exact:true}).selectOption("À visiter");
 await dialog.getByRole("button",{name:"Enregistrer",exact:true}).click();
 await expect(dialog.getByText("Fiche enregistrée.",{exact:true})).toBeVisible();
 await dialog.getByLabel("Votre commentaire",{exact:true}).fill("Test familial : examiner les travaux.");
 await dialog.getByRole("button",{name:"Publier le commentaire",exact:true}).click();
 await expect(dialog.getByText("Test familial : examiner les travaux.",{exact:true})).toBeVisible();
 await dialog.getByLabel("Date et heure",{exact:true}).fill("2030-11-10T14:00");
 await dialog.getByRole("button",{name:"Planifier la visite",exact:true}).click();
 await expect(dialog.getByRole("button",{name:"Annuler la visite",exact:true})).toBeVisible();
 await dialog.locator('input[type="file"]').setInputFiles("public/icon-192.png");
 await expect(dialog.getByText("Photo ajoutée.",{exact:true})).toBeVisible();
 await expect(dialog.locator(".photo-gallery img")).toHaveCount(1);
 const downloadPromise=page.waitForEvent("download");
 await dialog.getByRole("button",{name:"Télécharger le dossier PDF",exact:true}).click();
 const download=await downloadPromise;expect(download.suggestedFilename()).toBe("dossier-lbma.pdf");
 await download.saveAs("test-results/preview-dossier.pdf");
 await page.keyboard.press("Escape");
 await page.reload();
 await page.getByRole("button",{name:"Ouvrir la fiche ↗"}).first().click();
 await expect(page.getByRole("dialog").getByLabel("Apport (€)",{exact:true})).toHaveValue("20000");
 await expect(page.getByRole("dialog").getByText("Test familial : examiner les travaux.",{exact:true})).toBeVisible();
 await page.keyboard.press("Escape");
 await page.getByRole("button",{name:"Activer les notifications Android",exact:true}).click();
 await expect(page.getByText("Les notifications réelles sont désactivées dans la prévisualisation.",{exact:false})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(unexpected).toEqual([]);
});
