import {test,expect} from "@playwright/test";

test("SCI IS forecast: advanced inputs, after-tax cashflow and persistent saved property",async({page})=>{
 await page.setViewportSize({width:1440,height:900});
 const apiRequests:string[]=[];
 page.on("request",r=>{if(/supabase[.]|\/rest\/v1|\/api\//.test(r.url()))apiRequests.push(r.url());});
 await page.goto("./");
 await expect(page.getByRole("heading",{name:"Tableau de bord"})).toBeVisible();
 await page.getByRole("navigation",{name:"Navigation principale"}).getByRole("button",{name:"Calculateur"}).click();
 await page.getByLabel("Prix d'achat",{exact:true}).fill("100000");
 await page.getByLabel("Travaux",{exact:true}).fill("15000");
 await page.getByLabel("Loyer mensuel hors charges",{exact:true}).fill("1000");
 await page.getByLabel("Apport",{exact:true}).fill("20000");
 await page.getByLabel("Taux nominal",{exact:true}).fill("4");
 await page.getByLabel("Assurance emprunteur",{exact:true}).fill("0.3");
 await page.getByLabel("Taxe foncière",{exact:true}).fill("1000");
 await page.getByLabel("Charges non récupérables",{exact:true}).fill("400");
 await page.getByLabel("Assurance PNO",{exact:true}).fill("130");
 await page.getByLabel("Autres charges",{exact:true}).fill("250");
 await page.getByLabel("Gestion locative",{exact:true}).fill("6");
 const result=page.locator(".rb-sci-results");
 await expect(result.locator(".rb-sci-main-kpi strong")).toHaveText("—");
 await page.getByText("SCI à l'IS · Analyse avancée",{exact:true}).click();
 await page.getByLabel("Part de terrain non amortissable").fill("20");
 await page.getByLabel("Durée d'amortissement du bâtiment").fill("40");
 await page.getByLabel("Travaux immobilisés à l'acquisition").fill("15000");
 await page.getByLabel("Durée d'amortissement des travaux").fill("15");
 await page.getByLabel("Charges récupérables payées").fill("1000");
 await page.getByLabel("Remboursements locataires encaissés").fill("1000");
 await page.getByLabel("Comptable et administration SCI").fill("700");
 await page.getByLabel("CFE et taxes spécifiques").fill("0");
 await page.getByLabel("Entretien déductible hors travaux d'achat").fill("0");
 await page.getByLabel("Autre résultat fiscal annuel de la SCI").fill("0");
 await page.getByLabel("Déficits antérieurs reportables").fill("0");
 await page.getByLabel("Éligibilité de la SCI au taux réduit").selectOption("yes");
 await expect(result.locator(".rb-sci-main-kpi strong")).not.toHaveText("—");
 await expect(result).toContainText("Amortissement bâtiment");
 await expect(result).toContainText("Variation d'IS");
 await page.getByLabel("Nom pour enregistrer la simulation").fill("DÉMO · Calcul IS");
 await page.getByLabel("Commune pour enregistrer la simulation").fill("Valenciennes");
 await page.getByRole("button",{name:"Enregistrer comme bien"}).click();
 await expect(page.getByRole("heading",{name:"DÉMO · Calcul IS"})).toBeVisible();
 await expect(page.getByText("Dossier enregistré.")).toBeVisible();
 await expect(page.locator(".rb-sci-results .rb-sci-main-kpi strong")).not.toHaveText("—");
 await page.reload();
 await page.getByRole("navigation",{name:"Navigation principale"}).getByRole("button",{name:"Mes biens"}).click();
 await page.getByRole("button",{name:/DÉMO · Calcul IS/}).click();
 await page.getByText("SCI à l'IS · Analyse avancée",{exact:true}).click();
 await expect(page.getByLabel("Part de terrain non amortissable")).toHaveValue("20");
 await expect(page.getByLabel("Autre résultat fiscal annuel de la SCI")).toHaveValue("0");
 await expect(page.locator(".rb-sci-results .rb-sci-main-kpi strong")).not.toHaveText("—");
 expect(apiRequests).toEqual([]);
});

test("SCI IS on mobile: incomplete zero assumptions cannot display fictitious after-tax income",async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto("./");
 await page.getByRole("button",{name:"Ouvrir le menu"}).click();
 await page.getByRole("navigation",{name:"Navigation mobile"}).getByRole("button",{name:"Calculateur"}).click();
 const card=page.locator(".rb-sci-results");
 await expect(card.locator(".rb-sci-main-kpi strong")).toHaveText("—");
 await expect(card).toContainText("zéro non confirmé");
 await page.getByText("SCI à l'IS · Analyse avancée",{exact:true}).click();
 const check=page.getByRole("checkbox",{name:"Taxe foncière : montant nul confirmé"});
 await expect(check).not.toBeChecked();
 await check.check();
 await expect(check).toBeChecked();
 await page.getByLabel("Taxe foncière",{exact:true}).fill("850");
 await page.getByLabel("Taxe foncière",{exact:true}).fill("0");
 await expect(check).not.toBeChecked();
 await expect(card.locator(".rb-sci-main-kpi strong")).toHaveText("—");
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
