import {test,expect} from "@playwright/test";

test("V0.5.1 financial editing keeps provenance, warns on stale values and does not verify automatically",async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto("./");
 await page.getByRole("button",{name:"Ouvrir la fiche ↗"}).first().click();
 await expect(page.getByText("Exemple fictif · chiffres de démonstration",{exact:true})).toBeVisible();
 await page.getByText("Documenter les sources et justificatifs des chiffres",{exact:true}).click();
 const help=page.getByRole("button",{name:"À propos : Taxe foncière annuelle",exact:true}).first();
 await help.click();
 await expect(page.getByRole("tooltip")).toContainText("750 € par défaut");
 await page.keyboard.press("Escape");
 await expect(page.getByRole("tooltip")).toHaveCount(0);
 await page.getByRole("button",{name:"← Retour aux biens repérés",exact:true}).click();
 await page.getByRole("button",{name:"＋ Ajouter un bien",exact:true}).click();
 const dialog=page.getByRole("dialog");
 await dialog.getByLabel("Nom du bien",{exact:true}).fill("Contrôle provenance et hypothèses");
 await dialog.getByLabel("Ville",{exact:true}).fill("Beauvais");
 await dialog.getByLabel("Prix d’achat (€)",{exact:true}).fill("79000");
 await dialog.getByLabel("Surface (m²)",{exact:true}).fill("45");
 await dialog.getByLabel("Loyer mensuel (€)",{exact:true}).fill("600");
 await dialog.getByRole("button",{name:"Enregistrer",exact:true}).click();
 await page.getByText("Documenter les sources et justificatifs des chiffres",{exact:true}).click();
 await page.getByText("Documenter la source d’un indicateur",{exact:true}).click();
 await page.getByLabel("Source / justificatif",{exact:true}).fill("Avis du propriétaire (essai)");
 await page.getByLabel("Période des données (année ou date)",{exact:true}).fill("2025");
 await page.getByLabel("Périmètre (bien, commune ou quartier)",{exact:true}).fill("Logement de test");
 await page.locator(".lbma-detail-actions").getByRole("button",{name:"Enregistrer les modifications"}).click();
 await expect(page.locator(".lbma-dirty-state")).toContainText("enregistrées");
 await page.reload();
 await page.getByText("Documenter les sources et justificatifs des chiffres",{exact:true}).click();
 const row=page.getByRole("row").filter({has:page.getByRole("rowheader",{name:"Taxe foncière annuelle",exact:false})});
 await expect(row.getByText("Source déclarée · non contrôlée",{exact:true})).toBeVisible();
 await expect(row.getByText("2025 · Logement de test",{exact:true})).toBeVisible();
 await page.getByLabel("Taxe foncière annuelle",{exact:true}).fill("950");
 await expect(row.getByText("Valeur modifiée · source à revoir",{exact:true})).toBeVisible();
 await page.locator(".lbma-detail-actions").getByRole("button",{name:"Enregistrer les modifications"}).click();
 await page.reload();
 await page.getByText("Documenter les sources et justificatifs des chiffres",{exact:true}).click();
 const savedRow=page.getByRole("row").filter({has:page.getByRole("rowheader",{name:"Taxe foncière annuelle",exact:false})});
 await expect(savedRow.getByText("Valeur modifiée · source à revoir",{exact:true})).toBeVisible();
 await page.getByText("Documenter la source d’un indicateur",{exact:true}).click();
 await page.getByRole("combobox",{name:"Origine du chiffre",exact:true}).selectOption("ai");
 await expect(savedRow.getByText("Estimation IA · non validée",{exact:true})).toBeVisible();
 await page.getByText("Automatique ou manuel : comment obtenir les données ?",{exact:true}).click();
 await expect(page.getByText("État actuel : aucun des connecteurs ci-dessous n’est actif.",{exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test("V0.5.1 source editor remains keyboard accessible",async({page})=>{
 await page.setViewportSize({width:1440,height:1000});
 await page.goto("./");
 await page.getByRole("button",{name:"Ouvrir la fiche ↗"}).first().click();
 await page.getByText("Documenter les sources et justificatifs des chiffres",{exact:true}).click();
 const help=page.getByRole("button",{name:"À propos : Taxe foncière annuelle",exact:true}).first();
 await help.hover();await expect(page.getByRole("tooltip")).toBeVisible();
 await page.getByRole("heading",{name:"Simulation modifiable",exact:true}).hover();
 await expect(page.getByRole("tooltip")).toHaveCount(0);
 await help.focus();await expect(page.getByRole("tooltip")).toBeVisible();
 await page.keyboard.press("Escape");await expect(page.getByRole("tooltip")).toHaveCount(0);
 await page.getByRole("button",{name:"Options avancées / supprimer le bien",exact:true}).click();
 await expect(page.getByRole("dialog")).toBeVisible();
 await page.keyboard.press("Escape");
 await expect(page.getByRole("dialog")).toHaveCount(0);
});
